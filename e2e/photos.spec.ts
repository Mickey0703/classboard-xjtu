import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';

const png = readFileSync('class-emblem.png');
const image = { name: 'completion.png', mimeType: 'image/png', buffer: png };

test('inline photos survive drafts; required proof is enforced and appears privately in committee statistics', async ({ page, request, browser }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.context().addCookies([{ name: 'local_admin', value: 'test-token', domain: '127.0.0.1', path: '/' }]);
  const title = `照片流程 ${Date.now()}`;
  await page.goto('/?view=admin');
  await page.getByLabel('通知标题').fill(title);
  await page.getByLabel('通知正文').fill('照片前文。照片后文。');
  await page.getByLabel('通知正文').evaluate((element: HTMLTextAreaElement) => { element.focus(); element.setSelectionRange(5, 5); element.dispatchEvent(new Event('select', { bubbles: true })); });
  await page.getByLabel('添加照片', { exact: true }).setInputFiles(image);
  await expect(page.getByRole('img', { name: '通知照片 1', exact: true })).toBeVisible();
  await page.getByLabel('类型').selectOption('task');
  await page.getByRole('checkbox', { name: '须提交完成凭据' }).check();
  await page.getByLabel('截止时间', { exact: true }).fill('2026-10-05T18:00');
  await page.getByRole('button', { name: '保存草稿' }).click();
  const row = page.locator('.admin-notice-row').filter({ hasText: title });
  await expect(row).toBeVisible();
  await page.reload();
  await page.getByRole('navigation', { name: '班委管理菜单' }).getByRole('button', { name: '通知记录', exact: true }).click();
  await row.getByRole('button', { name: '编辑草稿' }).click();
  await expect(page.getByRole('checkbox', { name: '须提交完成凭据' })).toBeChecked();
  await expect(page.getByRole('img', { name: '通知照片 1', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '取消编辑' }).click();
  await page.getByRole('navigation', { name: '班委管理菜单' }).getByRole('button', { name: '通知记录', exact: true }).click();
  await row.getByRole('button', { name: '发布通知' }).click();
  await expect(row.getByText(/已发布/)).toBeVisible();
  const snapshot = await (await request.get('/api/snapshot')).json();
  const notice = snapshot.notifications.find((n: { title: string }) => n.title === title);
  expect(notice.photos).toHaveLength(1);
  expect(notice.photos[0].position).toBe(5);
  expect(notice.requiresCompletionProof).toBe(true);
  expect(notice.photos[0].dataUrl.length).toBeLessThanOrEqual(400_000);

  await page.context().addCookies([{ name: 'local_member', value: 'member-test', domain: '127.0.0.1', path: '/' }]);
  await page.goto('/?view=notifications');
  const card = page.locator('.notice-card').filter({ hasText: title });
  const noProof = await page.request.post('/api/member/receipt', { data: { notificationId: notice.id, action: 'complete', photos: [] } });
  expect(noProof.status()).toBe(400);
  await card.getByRole('button', { name: '放大通知照片 1', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '通知照片 1' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await card.getByRole('button', { name: '标记已完成' }).click();
  const dialog = page.getByRole('dialog', { name: '提交完成照片' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText('请添加完成照片或截图，供班委查看。', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(card.getByRole('button', { name: '标记已完成' })).toBeVisible();
  await card.getByRole('button', { name: '标记已完成' }).click();
  await dialog.getByLabel('添加完成照片').setInputFiles({ name: 'bad.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') });
  await expect(dialog.getByRole('alert')).toHaveText('请选择 JPG、PNG 或 WebP 照片');
  await dialog.getByLabel('添加完成照片').setInputFiles(image);
  await expect(dialog.getByRole('img', { name: '已选照片 1' })).toBeVisible();
  await dialog.getByRole('button', { name: '删除照片 1' }).click();
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeDisabled();
  await dialog.getByLabel('添加完成照片').setInputFiles(image);
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeEnabled();
  await page.screenshot({ path: 'test-results/completion-upload-mobile.png' });
  expect(await dialog.evaluate(element => element.getBoundingClientRect().right <= window.innerWidth)).toBe(true);
  await dialog.getByRole('button', { name: '确认', exact: true }).click();
  await expect(card.getByRole('button', { name: '撤销完成' })).toBeVisible();
  await page.reload();
  await expect(card.getByRole('img', { name: '完成照片 1', exact: true })).toBeVisible();
  const own = await (await page.request.get('/api/member/receipt')).json();
  const receipt = own.find((r: { notificationId: string }) => r.notificationId === notice.id);
  expect(receipt.photos).toHaveLength(1);
  const publicSnapshot = await (await request.get('/api/snapshot')).text();
  expect(publicSnapshot).not.toContain(receipt.photos[0].id);
  const anonymous = await browser.newContext();
  try {
    expect((await anonymous.request.get(`${new URL(page.url()).origin}/api/member/receipt`)).status()).toBe(403);
    expect((await anonymous.request.get(`${new URL(page.url()).origin}/api/admin/notification-stats?id=${notice.id}`)).status()).toBe(403);
    expect((await anonymous.request.get(`${new URL(page.url()).origin}${receipt.photos[0].dataUrl}`)).status()).toBe(403);
  } finally { await anonymous.close(); }

  await page.goto('/?view=admin');
  await page.getByRole('navigation', { name: '班委管理菜单' }).getByRole('button', { name: '通知记录', exact: true }).click();
  await row.getByRole('button', { name: '查看统计' }).click();
  await expect(page.getByRole('heading', { name: '已完成同学与照片' })).toBeVisible();
  const proof = page.getByRole('button', { name: '放大演示同学甲的完成照片 1', exact: true });
  await expect(proof).toBeVisible();
  await proof.click();
  await expect(page.getByRole('dialog', { name: '演示同学甲的完成照片 1' })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'test-results/completion-stats-mobile.png', fullPage: true });
  await page.goto('/?view=notifications');
  await card.getByRole('button', { name: '撤销完成' }).click();
  await expect(card.getByRole('button', { name: '标记已完成' })).toBeVisible();
  await expect(card.getByRole('img', { name: '完成照片 1', exact: true })).toHaveCount(0);
  await page.goto('/?view=admin');
  await page.getByRole('navigation', { name: '班委管理菜单' }).getByRole('button', { name: '通知记录', exact: true }).click();
  await row.getByRole('button', { name: '查看统计' }).click();
  await expect(page.getByText('暂无已完成同学')).toBeVisible();
  await row.getByRole('button', { name: '撤回并编辑' }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认撤回并编辑' }).click();
  await expect(page.getByRole('heading', { name: '编辑通知草稿' })).toBeVisible();
});

import { expect, test } from '@playwright/test';

test('mobile committee filters records, restores the same draft and confirms scoped deletion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.context().addCookies([{ name: 'local_admin', value: 'test-token', domain: '127.0.0.1', path: '/' }]);
  const prefix = `记录管理 ${Date.now()}`;
  const create = async (title: string, kind = 'notice') => {
    const response = await page.request.post('/api/admin/notifications', { data: { title, kind, priority: 'normal', body: '原通知正文', pinned: false, dueAt: kind === 'task' ? '2000-01-01T00:00:00+08:00' : null } });
    expect(response.status()).toBe(200);
    const { id } = await response.json() as { id: string };
    expect((await page.request.patch('/api/admin/notifications', { data: { id, action: 'publish' } })).status()).toBe(200);
    return id;
  };
  const active = await create(`${prefix} 公告`);
  const expired = await create(`${prefix} 逾期`, 'task');
  const withdrawn = await create(`${prefix} 撤回`);
  await page.request.patch('/api/admin/notifications', { data: { id: withdrawn, action: 'withdraw' } });
  await page.goto('/?view=admin');
  await page.getByRole('navigation', { name: '班委管理菜单' }).getByRole('button', { name: '通知记录', exact: true }).click();
  const filters = page.getByRole('navigation', { name: '通知记录分类' });
  await filters.getByRole('button', { name: /已撤回/ }).click();
  const row = page.locator('.admin-notice-row').filter({ hasText: `${prefix} 撤回` });
  await row.getByRole('button', { name: '重新编辑' }).click();
  await page.getByRole('dialog').getByRole('button', { name: '恢复并编辑' }).click();
  await expect(page.getByLabel('通知正文')).toHaveValue('原通知正文');
  const records = await (await page.request.get('/api/admin/notifications')).json() as { id: string; status: string }[];
  expect(records.find(record => record.id === withdrawn)?.status).toBe('draft');
  await page.getByRole('button', { name: '保存草稿' }).click();
  await row.getByRole('button', { name: '发布通知' }).click();
  await expect(row.getByText('已发布')).toBeVisible();
  await row.getByRole('button', { name: '撤回并编辑' }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认撤回并编辑' }).click();
  await expect(page.getByLabel('通知正文')).toHaveValue('原通知正文');
  await page.getByRole('button', { name: '保存草稿' }).click();
  await row.getByRole('button', { name: '发布通知' }).click();
  await expect(row.getByText('已发布')).toBeVisible();
  await page.request.patch('/api/admin/notifications', { data: { id: withdrawn, action: 'withdraw' } });
  await page.reload();
  await page.getByRole('navigation', { name: '班委管理菜单' }).getByRole('button', { name: '通知记录', exact: true }).click();
  await filters.getByRole('button', { name: /已撤回/ }).click();
  await row.getByRole('checkbox').check();
  await page.getByRole('button', { name: '删除所选' }).click();
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click();
  await expect(row).toBeVisible();
  await page.getByRole('button', { name: '删除所选' }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认删除' }).click();
  await expect(row).toHaveCount(0);
  await filters.getByRole('button', { name: /已逾期/ }).click();
  await expect(page.getByText(`${prefix} 逾期`, { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/record-management-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '删除所有已逾期通知', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认删除' }).click();
  await expect(page.getByText('当前分类暂无通知')).toBeVisible();
  const after = await (await page.request.get('/api/admin/notifications')).json() as { id: string }[];
  expect(after.some(record => record.id === active)).toBe(true);
  expect(after.some(record => record.id === expired || record.id === withdrawn)).toBe(false);
  await page.request.patch('/api/admin/notifications', { data: { id: active, action: 'withdraw' } });
  await page.request.delete('/api/admin/notifications', { data: { ids: [active], category: 'withdrawn' } });
});
